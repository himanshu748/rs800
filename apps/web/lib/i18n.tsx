export type Key = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict];

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("rs800.lang");
      // eslint-disable-next-line react-hooks/set-state-in-effect -- localStorage is only readable after mount in a static export
      if (saved === "hi" || saved === "en") setLangState(saved);
    } catch {}
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("rs800.lang", l);
    } catch {}
  };
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}

export function fill(s: string, vars: Record<string, string | number> = {}) {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function useT() {
  const { lang } = useLang();
  const d = dicts[lang];
  const t = (k: Key, vars?: Record<string, string | number>) => fill(d[k], vars);
  return { t, d, lang };
}

const CITY_HI: Record<string, string> = { Lucknow: "लखनऊ", Delhi: "दिल्ली", Jaipur: "जयपुर", Ahmedabad: "अहमदाबाद", Mumbai: "मुंबई" };

export function cityName(c: string, lang: Lang) {
  return lang === "hi" ? CITY_HI[c] ?? c : c;
}

export function inr(n: number) {
  return "₹" + new Intl.NumberFormat("en-IN").format(Math.round(n));
}
